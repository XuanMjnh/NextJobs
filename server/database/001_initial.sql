CREATE TABLE IF NOT EXISTS users (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 email VARCHAR(190) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 role ENUM('candidate','recruiter') NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS profiles (
 user_id INT UNSIGNED PRIMARY KEY,
 first_name VARCHAR(100) NOT NULL DEFAULT '', last_name VARCHAR(100) NOT NULL DEFAULT '',
 city VARCHAR(200) NOT NULL DEFAULT '', state VARCHAR(200) NOT NULL DEFAULT '', country VARCHAR(200) NOT NULL DEFAULT '',
 company VARCHAR(200) NOT NULL DEFAULT '', certificate VARCHAR(200) NOT NULL DEFAULT '', experience VARCHAR(1000) NOT NULL DEFAULT '',
 photo VARCHAR(100), resume VARCHAR(100),
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS skills (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id INT UNSIGNED NOT NULL,
 name VARCHAR(100) NOT NULL, level ENUM('Beginner','Intermediate','Advance') NOT NULL,
 years DECIMAL(4,1) NOT NULL DEFAULT 0,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS jobs (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, recruiter_id INT UNSIGNED NOT NULL,
 title VARCHAR(200) NOT NULL, company VARCHAR(200) NOT NULL, logo VARCHAR(100),
 city VARCHAR(200) NOT NULL, state VARCHAR(200) NOT NULL DEFAULT '', country VARCHAR(200) NOT NULL DEFAULT 'Việt Nam',
 type ENUM('Full-time','Part-time','Freelance','Internship') NOT NULL,
 remote ENUM('Remote-Only','Office-Only','Partial-Remote') NOT NULL,
 salary VARCHAR(100) NOT NULL, quantity INT UNSIGNED NOT NULL DEFAULT 1,
 field VARCHAR(200) NOT NULL DEFAULT '', experience_required VARCHAR(200) NOT NULL DEFAULT '', certificate_required VARCHAR(200) NOT NULL DEFAULT '',
 description TEXT NOT NULL, status ENUM('open','closed') NOT NULL DEFAULT 'open',
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY(recruiter_id) REFERENCES users(id), INDEX idx_job_created(created_at), INDEX idx_job_owner(recruiter_id,status)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS saved_jobs (
 user_id INT UNSIGNED NOT NULL, job_id INT UNSIGNED NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(user_id, job_id), FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,
 FOREIGN KEY(job_id) REFERENCES jobs(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS applications (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id INT UNSIGNED NOT NULL, job_id INT UNSIGNED NOT NULL,
 resume VARCHAR(100) NOT NULL, cover_letter TEXT NOT NULL,
 status ENUM('pending','reviewing','accepted','rejected','withdrawn') NOT NULL DEFAULT 'pending',
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, UNIQUE KEY unique_application(user_id,job_id),
 FOREIGN KEY(user_id) REFERENCES users(id), FOREIGN KEY(job_id) REFERENCES jobs(id), INDEX idx_application_job(job_id)
) ENGINE=InnoDB;
